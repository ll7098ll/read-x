def enrich(sets):
 import hashlib,json
 from pathlib import Path
 root=Path(__file__).resolve().parents[1]
 standards={r['id']:r for r in json.loads((root/'data/curriculum_2022/achievement_standards.json').read_text(encoding='utf-8'))}
 for s in sets:
  if s['microSkillId']!='plan-G5-literature-06':continue
  key=s['stage']+'-'+s['variant'];cursor=0;s['poems']=[]
  for i,(title,lines) in enumerate(POEMS[key],1):
   block=s['paragraphs'][cursor:cursor+len(lines)+1]
   assert [p['text'] for p in block[1:]]==lines
   s['poems'].append(dict(id=s['id']+'-P'+str(i),title=title,headingParagraphId=block[0]['id'],lineParagraphIds=[p['id'] for p in block[1:]],lines=lines))
   cursor+=len(lines)+1
  s['poetryHash']=hashlib.sha256(json.dumps(s['poems'],ensure_ascii=False,sort_keys=True).encode()).hexdigest()
  s['textDemand'].update(format='자체 창작 자유시와 감상 상황',lineBreaks='원시의 행 구분 보존',genre='poetry')
  s['taskDemand']['evidenceDistance']='시의 여러 행 또는 두 시 사이' if s['stage'] in ('S3','S4','S5','S6') else '시의 가까운 행'
  s['source']['authorship']='이 파일에서 새로 집필한 창작시·감상 상황; 기존 작품 인용 없음'
  codes=['6국05-04']
  if key in ('S2-A','S2-B','S3-A','S6-A','S6-B'):codes.append('6국05-02')
  refs=[]
  for code in codes:
   r=standards[code];file=root/r['sourcePath'];line=file.read_text(encoding='utf-8').splitlines()[r['sourceLine']-1]
   assert code in line and r['statement'] in line
   refs.append(dict(code=code,statement=r['statement'],gradeBand=r['gradeBand'],sourcePath=r['sourcePath'],sourceLine=r['sourceLine'],noticeVersion=r['noticeVersion'],sourceHash=hashlib.sha256(file.read_bytes()).hexdigest(),alignmentState='source_text_checked_candidate'))
  s['source']['officialStandards']=refs
  s['review']['curriculumAlignment']='작품 의견 나누기·해당 자료의 비유 효과에 대한 단원 수준 연결 후보. 특정 학년 배치와 개별 문항 범위는 교사 검토 대기.'
  for q in s['questions']:
   if q['kind']!='single_choice':q['acceptableResponses']='다른 정서어·해석도 실제 시구와 관계를 설명하면 수용한다. 시구가 지지하지 않는 사건·작가 이력의 단정은 구별한다. 답시의 새 감정과 상상은 예시와 같을 필요가 없으며 원시의 사실이라고 주장하는 것과 구별한다.'
   if q['kind']!='writing':continue
   q['rubric']=[dict(criterion=c,levels={'0':bad,'1':partial,'2':full}) for c,bad,partial,full in WRITING[key]]
   q['planningPrompt']='내 해석 / 근거 시구 / 두 내용이 연결되는 까닭을 먼저 적으세요.'
   if key=='S6-A':q['planningPrompt']='관람객에게 알릴 차이 / 시 가의 표현 / 시 나의 표현 / 초안에서 고칠 단정을 메모하세요.'
   if key=='S6-B':q['planningPrompt']='답하는 대상 / 원시에서 반응할 말·행동 / 새로 상상한 마음과 장면을 메모하세요. 예시와 다른 마음도 근거와 연결되면 좋습니다.'
