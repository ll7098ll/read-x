test('independent institutions keep separate approvals and local recovery cannot create an owner',async t=>{
  const {mkdtemp,rm}=await import('node:fs/promises'),{join,resolve}=await import('node:path'),{tmpdir}=await import('node:os');
  const {DatabaseSync}=await import('node:sqlite'),{randomUUID}=await import('node:crypto'),{spawnSync}=await import('node:child_process');
  const dir=await mkdtemp(join(tmpdir(),'readx-org-test-'));if(!resolve(dir).startsWith(resolve(tmpdir())))throw Error('Unexpected temp path');
  const dbPath=join(dir,'org.sqlite'),f=await fixture(t,{dbPath});t.after(async()=>{await f.close();await rm(dir,{recursive:true,force:true});});
  const db=new DatabaseSync(dbPath),state=JSON.parse(db.prepare('SELECT body FROM exam_state WHERE id=1').get().body);
  const original=state.users.find(u=>u.username==='owner'),tenantId=randomUUID(),classId=randomUUID();
  state.organizations.push({id:tenantId,name:'다른 기관',revision:0});state.classes.push({id:classId,tenantId,name:'독립 반',active:true,revision:0});
  state.users.push({...original,id:randomUUID(),username:'other_owner',tenantId,classIds:[classId],className:'독립 반'});
  const otherStudent={...state.users.find(u=>u.username==='student1'),id:randomUUID(),username:'other_student',tenantId,classId,className:'독립 반'};state.users.push(otherStudent);
  db.prepare('UPDATE exam_state SET body=? WHERE id=1').run(JSON.stringify(state));db.close();
  const other=f.client();await other('/login',{username:'other_owner',password});
  const first=(await f.owner('/learning/catalog')).lessons[0],preview=await f.owner('/learning/catalog/'+first.id);
  await f.owner('/learning/approvals',{lessonId:first.id,contentHash:preview.contentHash,note:'첫 기관 시범 검토',pilot:true});
  await other('/learning/approvals',{lessonId:first.id,contentHash:preview.contentHash,note:'다른 기관의 독립 검토',pilot:true});
  assert.equal((await f.owner('/learning/catalog')).lessons.find(l=>l.id===first.id).approved,true);
  assert.equal((await other('/learning/catalog')).lessons.find(l=>l.id===first.id).approved,true);
  await f.owner('/org/classes/'+classId,{name:'다른 기관 수정',active:true,revision:0},404);
  await f.owner('/assignments',{studentIds:[otherStudent.id],opensAt:Date.now()-1000,closesAt:Date.now()+3600000},400);
  const denied=spawnSync(process.execPath,['server/recover-owner.mjs','--db',dbPath,'--username','student1'],{encoding:'utf8'});assert.equal(denied.status,1);
  const recovery=spawnSync(process.execPath,['server/recover-owner.mjs','--db',dbPath,'--username','owner'],{encoding:'utf8'});assert.equal(recovery.status,0,recovery.stderr);
  const code=recovery.stdout.trim().split(/\r?\n/).at(-1);assert.match(code,/^[a-f0-9]{64}$/);
  const anonymous=f.client();await anonymous('/recover',{username:'owner',code,newPassword:'Recovered-Owner-2026'});
  await f.owner('/dashboard',undefined,401);
  await f.owner('/login',{username:'owner',password:'Recovered-Owner-2026'});assert.equal((await f.owner('/session')).user.isOwner,true);
});
