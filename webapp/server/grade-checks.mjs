export function gradeChecks(grade,course){
 const data=(rows[grade]||upperRows[grade])?.[course];if(!data)return null;
 return data.map(([title,text,prompt,...options],i)=>{
  const paragraphs=text.split('\n'),offset=i%options.length;
  return {id:`g${grade}-${course}-check-${i}`,familyId:`course-source:${course}:${i}`,title,paragraphs,prompt,
   options:options.slice(offset).concat(options.slice(0,offset)),answer:(options.length-offset)%options.length,evidence:paragraphs.map((_,i)=>i),
   rubric:`${courseNames[course]}: 선택한 답과 글의 단서를 연결해 ${grade<=2?'낱말이나 짧은 말':'관계와 조건을 갖춘 말'}로 설명했는지 확인합니다.`,
   grade,oralAllowed:gradeProfiles[grade].oralAllowed,version:2};
 });
}
